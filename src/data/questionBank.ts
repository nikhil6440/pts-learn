/**
 * Retrieves exactly 3 high-quality, relevant educational questions for a given game, world, and level.
 * Never generates generic "Option A/B/C/D" placeholders.
 */
export function getFallbackQuestionsForLevel(
  gameId: GameId,
  worldNumber: number,
  levelNumber: number,
  ageGroup: string = '10-11',
  difficulty: string = 'medium'
): QuizQuestion[] {
  // Pool of all questions for this game
  const gamePool = LOCAL_QUESTION_BANK.filter((q) => q.gameId === gameId);

  // Exact matches for this world & level
  const exactMatches = gamePool.filter(
    (q) => q.worldNumber === worldNumber && q.levelNumber === levelNumber
  );

  if (exactMatches.length >= 3) {
    return exactMatches.slice(0, 3);
  }

  // Same world matches
  const worldMatches = gamePool.filter((q) => q.worldNumber === worldNumber);

  const selected: QuizQuestion[] = [...exactMatches];
  const candidates = worldMatches.length >= 3 ? worldMatches : gamePool;

  for (let i = 0; selected.length < 3; i++) {
    const candidate = candidates[(levelNumber + i) % candidates.length];
    if (!selected.some((s) => s.questionText === candidate.questionText)) {
      selected.push({
        ...candidate,
        questionId: `${candidate.questionId}-w${worldNumber}l${levelNumber}-${selected.length}`,
        worldNumber,
        levelNumber,
      });
    } else if (i > candidates.length * 2) {
      // Avoid infinite loop if pool small
      selected.push({
        ...candidate,
        questionId: `${candidate.questionId}-var-${Date.now()}-${selected.length}`,
        worldNumber,
        levelNumber,
      });
    }
  }

  return selected.slice(0, 3);
}
